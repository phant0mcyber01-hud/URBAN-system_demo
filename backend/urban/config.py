"""Paths and settings (.env in the repo root overrides defaults)."""
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data"
OUT = DATA / "out"    # the demo twin: map layers and synthetic junctions built with SUMO
CITY = DATA / "city"  # the real city: map layers from OSM and the junction passports (python -m urban.city)
WEB_DIST = ROOT / "web" / "dist"

_env = ROOT / ".env"
if _env.exists():
    for line in _env.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            os.environ.setdefault(k.strip(), v.strip())

BBOX = os.getenv("BBOX", "71.770,40.372,71.800,40.398")  # west,south,east,north
SIM_SPEEDUP = float(os.getenv("SIM_SPEEDUP", "1"))
SIM_END = int(os.getenv("SIM_END", "3600"))
CAR_PERIOD = float(os.getenv("CAR_PERIOD", "0.6"))
BUS_PERIOD = int(os.getenv("BUS_PERIOD", "120"))
INCIDENT_AT = int(os.getenv("INCIDENT_AT", "120"))
INCIDENT_DURATION = int(os.getenv("INCIDENT_DURATION", "240"))
# field (the default): the real system. A clock is the source, queues come only from real URBAN Edge units,
#   the map and the junctions are the city's own (data/city).
# simulation: the demo twin for presentations and measurements. SUMO drives traffic, the platform starts an
#   emulated Edge fleet, the map and the junctions are synthetic (data/out). Needs `pip install -e "backend[demo]"`.
SOURCE = os.getenv("URBAN_SOURCE", "field")
DEMO = SOURCE == "simulation"
MAP = OUT if DEMO else CITY  # served to the UI as /data
HOST = os.getenv("HOST", "127.0.0.1")  # UI and API; behind a reverse proxy on a server
PORT = int(os.getenv("PORT", "8080"))
# the interface over HTTPS with the platform's own server certificate (URBAN OS, role center: no reverse proxy)
UI_TLS = os.getenv("UI_TLS", "off").lower() in ("on", "1", "true", "yes")
DEVICE_HOST = os.getenv("DEVICE_HOST", "127.0.0.1")  # TLS listener for URBAN Edge devices; 0.0.0.0 on a server
DEVICE_PORT = int(os.getenv("DEVICE_PORT", "8443"))
DEVICE_NAME = os.getenv("DEVICE_NAME", "localhost")  # host name the devices connect to; goes on the certificate
# the demo twin keeps its keys, devices and history apart, so a presentation never mixes with the real city
STATE = DATA / "demo" if DEMO else DATA
PKI = STATE / "pki"  # keys and certificates, generated by `python -m urban.provision`
