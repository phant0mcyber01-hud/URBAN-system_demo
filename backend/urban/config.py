# green corridor proposals for emergency units: off by default, the measurement showed no clear benefit
# from plan selection (docs/corridor.md); on for trials
GREEN_CORRIDOR = os.getenv("GREEN_CORRIDOR", "off").lower() in ("on", "1", "true", "yes")


def sumo_home() -> Path:
    """SUMO is needed only by the demo twin and the measurements, so it is imported on demand."""
    try:
        import sumo
    except ImportError:
        raise SystemExit('SUMO is not installed: it is needed only for the demo twin, pip install -e "backend[demo]"')
    return Path(sumo.SUMO_HOME)


def __getattr__(name):  # config.SUMO_HOME / SUMO_BIN / SUMO_TOOLS, resolved when first used
    if name in ("SUMO_HOME", "SUMO_BIN", "SUMO_TOOLS"):
        home = sumo_home()
        return {"SUMO_HOME": home, "SUMO_BIN": home / "bin", "SUMO_TOOLS": home / "tools"}[name]
    raise AttributeError(name)


def sumo_env():
    env = dict(os.environ)
    home = sumo_home()
    env["SUMO_HOME"] = str(home)
    env["PATH"] = str(home / "bin") + os.pathsep + env.get("PATH", "")
    return env
